"""Writes limbo.ts from x509-limbo's limbo.json.

usage: emit-ts.py <limbo.json> <commit> > limbo.ts

Keeps every test case except the BetterTLS ones (about 9,600 cases and 24 MB of
certificates, too large to commit). Certificates and CRLs are stored once each, as base64
DER, and the cases refer to them by index, so the output is browser-safe and small.
"""

import base64
import json
import re
import sys

limbo = json.load(open(sys.argv[1], encoding='utf-8'))
commit = sys.argv[2]
assert limbo['version'] == 1


def der(pem):
    body = re.sub(r'-----[A-Z0-9 ]+-----', '', pem)
    return base64.b64encode(base64.b64decode(''.join(body.split()))).decode()


blobs = []
index = {}


def ref(pem):
    value = der(pem)
    if value not in index:
        index[value] = len(blobs)
        blobs.append(value)
    return index[value]


cases = []
for t in limbo['testcases']:
    if t['id'].startswith('bettertls::'):
        continue
    case = {
        'id': t['id'],
        'description': t['description'].strip(),
        'kind': t['validation_kind'],
        'trusted': [ref(c) for c in t['trusted_certs']],
        'untrusted': [ref(c) for c in t['untrusted_intermediates']],
        'peer': ref(t['peer_certificate']),
        'crls': [ref(c) for c in t.get('crls') or []],
        'expected': t['expected_result'],
    }
    optional = {
        'validationTime': t.get('validation_time'),
        'peerName': t.get('expected_peer_name'),
        'peerNames': t.get('expected_peer_names') or None,
        'keyUsage': t.get('key_usage') or None,
        'extendedKeyUsage': t.get('extended_key_usage') or None,
        'signatureAlgorithms': t.get('signature_algorithms') or None,
        'maxChainDepth': t.get('max_chain_depth'),
        'features': t.get('features') or None,
        'conflictsWith': t.get('conflicts_with') or None,
    }
    case.update({k: v for k, v in optional.items() if v is not None})
    cases.append(case)

print(f'''// Generated by generate.sh from x509-limbo (https://github.com/C2SP/x509-limbo,
// Apache-2.0) at commit {commit}; do not edit.
// The BetterTLS cases are left out. Certificates and CRLs are base64 DER, referred to
// by index.

export type LimboCase = {{
    id: string
    description: string
    kind: 'SERVER' | 'CLIENT'
    trusted: number[]
    untrusted: number[]
    peer: number
    crls: number[]
    expected: 'SUCCESS' | 'FAILURE'
    validationTime?: string
    peerName?: {{ kind: 'DNS' | 'IP' | 'RFC822'; value: string }}
    peerNames?: {{ kind: 'DNS' | 'IP' | 'RFC822'; value: string }}[]
    keyUsage?: string[]
    extendedKeyUsage?: string[]
    signatureAlgorithms?: string[]
    maxChainDepth?: number
    features?: string[]
    conflictsWith?: string[]
}}

export const limboBlobs: string[] = {json.dumps(blobs, indent=4)}

export const limboCases: LimboCase[] = {json.dumps(cases, indent=4)}''')
