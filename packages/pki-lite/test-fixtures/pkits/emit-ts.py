"""Writes pkits.ts from the PKITS specification text and certificates.

usage: emit-ts.py <PKITS.txt from `pdftotext -layout`> <certs dir> > pkits.ts

For every test in sections 4.8 to 4.13 it reads the certification path from the
specification ("Certification Path: ... composed of the following objects") and maps
each object name to its file ("Good CA Cert" -> GoodCACert.crt). CRLs are left out:
these sections test policy and name processing, not revocation.
"""

import base64
import json
import os
import re
import sys

SECTIONS = r'(?:8|9|1[0-3])'

text = open(sys.argv[1], encoding='utf-8').read().replace('\f', '\n')
certs_dir = sys.argv[2]

start = text.index('\n4.8.1 All Certificates Same Policy Test1')
end = re.search(r'\n4\.14\s+Distribution', text).start()
body = text[start:end]

headings = [
    (m.start(), m.group(1), m.group(2).strip())
    for m in re.finditer(r'\n(4\.' + SECTIONS + r'\.\d+) ([^\n]+)\n', body)
]

tests = []
for i, (pos, test_id, title) in enumerate(headings):
    chunk = body[pos : headings[i + 1][0] if i + 1 < len(headings) else len(body)]
    # the last test of a section is followed by the next section's introduction
    section = re.search(r'\n4\.\d+ [A-Z][^\n]*\n', chunk[1:])
    if section:
        chunk = chunk[: section.start() + 1]
    listing = chunk.split('Certification Path:')[-1]
    # drop page-number lines, so names wrapped across a page break join up again
    listing = '\n'.join(
        line for line in listing.split('\n') if not re.fullmatch(r'\s*\d+\s*', line)
    )
    path = []
    for bullet in listing.split('•')[1:]:
        for obj in re.sub(r'\s+', ' ', bullet).split(','):
            name = obj.strip().replace(' ', '').replace('-', '')
            if name.endswith(('Cert', 'Certificate', 'EE')):
                path.append(name)
    if path[0] != 'TrustAnchorRootCertificate' or not path[-1].endswith('EE'):
        sys.exit(f'{test_id}: unexpected path {path}')
    for name in path:
        if not os.path.exists(f'{certs_dir}/{name}.crt'):
            sys.exit(f'{test_id}: no certificate {name}.crt')
    tests.append({'id': test_id, 'title': title, 'path': path})

names = sorted({name for test in tests for name in test['path']})


def b64(name):
    with open(f'{certs_dir}/{name}.crt', 'rb') as f:
        return base64.b64encode(f.read()).decode()


out = [
    '// Generated by generate.sh from NIST PKITS (sections 4.8 to 4.13). Do not edit.',
    '// See README.md for the source and how to regenerate.',
    '',
    '/** Certificate file name (without .crt) -> base64 DER */',
    'export const pkitsCertificates: Record<string, string> = {',
]
out += [f"    {name}: '{b64(name)}'," for name in names]
out += [
    '}',
    '',
    '/** Each test: its PKITS number, title and path, trust anchor first, end entity last */',
    'export const pkitsTests: { id: string; title: string; path: string[] }[] = [',
]
for test in tests:
    out.append(
        f"    {{ id: '{test['id']}', title: {json.dumps(test['title'])}, path: {json.dumps(test['path'])} }},"
    )
out += [']', '']
sys.stdout.write('\n'.join(out))
print(f'{len(tests)} tests, {len(names)} certificates', file=sys.stderr)
