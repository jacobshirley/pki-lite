"""Writes pkits.ts from the PKITS specification text and certificates.

usage: emit-ts.py <PKITS.txt from `pdftotext -layout`> <data dir> > pkits.ts

For every test in section 4 it reads the objects the specification lists for the
certification path ("Certification Path: ... composed of the following objects") and maps
each name to its file: "Good CA Cert" -> certs/GoodCACert.crt, "Good CA CRL" ->
crls/GoodCACRL.crl.
"""

import base64
import json
import os
import re
import sys

SECTIONS = r'(?:[1-9]|1[0-6])'

text = open(sys.argv[1], encoding='utf-8').read().replace('\f', '\n')
data_dir = sys.argv[2]


def file_of(name):
    if name.endswith('CRL'):
        return f'{data_dir}/crls/{name}.crl'
    return f'{data_dir}/certs/{name}.crt'


start = re.search(r'\n\s*4\.1\.1 Valid Signatures Test1', text).start()
# (searched after the start: the table of contents has the same heading)
end = start + re.search(r'\n\s*5 Relationship to Previous Test Suite', text[start:]).start()
body = text[start:end]

headings = [
    (m.start(), m.group(1), m.group(2).strip())
    for m in re.finditer(r'\n\s*(4\.' + SECTIONS + r'\.\d+) ([^\n]+)\n', body)
]

tests = []
for i, (pos, test_id, title) in enumerate(headings):
    chunk = body[pos : headings[i + 1][0] if i + 1 < len(headings) else len(body)]
    # the last test of a section is followed by the next section's introduction
    section = re.search(r'\n\s*4\.\d+ [A-Z][^\n]*\n', chunk[1:])
    if section:
        chunk = chunk[: section.start() + 1]
    listing = chunk.split('Certification Path:')[-1]
    # drop page-number lines, so names wrapped across a page break join up again
    listing = '\n'.join(
        line for line in listing.split('\n') if not re.fullmatch(r'\s*\d+\s*', line)
    )
    path = []
    for bullet in listing.split('•')[1:]:
        for obj in re.sub(r'\s+', ' ', bullet).split(','):
            # an end entity's name ends at its last "EE" (a footnote may follow); other names
            # end at their last Cert/Certificate/CRL word, or one ending in CRL as in
            # "deltaCRL CA1 deltaCRL" (names such as "pre2000 CRL nextUpdate CA Cert" contain
            # those words earlier)
            words = obj.split()
            if 'EE' in words:
                end = len(words) - 1 - words[::-1].index('EE')
            else:
                ends = [
                    i
                    for i, word in enumerate(words)
                    if word in ('Cert', 'Certificate', 'CRL')
                    or (i > 0 and word.endswith('CRL'))
                ]
                if not ends:
                    continue
                end = ends[-1]
            path.append(''.join(words[: end + 1]).replace('-', ''))
    if path[0] != 'TrustAnchorRootCertificate' or not path[-1].endswith('EE'):
        sys.exit(f'{test_id}: unexpected path {path}')
    for name in path:
        if not os.path.exists(file_of(name)):
            sys.exit(f'{test_id}: no file for {name}')
    tests.append({'id': test_id, 'title': title, 'path': path})

names = sorted({name for test in tests for name in test['path']})


def b64(name):
    with open(file_of(name), 'rb') as f:
        return base64.b64encode(f.read()).decode()


out = [
    '// Generated by generate.sh from NIST PKITS (section 4). Do not edit.',
    '// See README.md for the source and how to regenerate.',
    '',
    '/** Certificate and CRL file names (without .crt / .crl) -> base64 DER */',
    'export const pkitsFiles: Record<string, string> = {',
]
out += [f"    {name}: '{b64(name)}'," for name in names]
out += [
    '}',
    '',
    '/**',
    ' * Each test: its PKITS number, title and the objects the specification lists for it',
    ' * (certificates and CRLs, names ending in CRL), trust anchor first, end entity last',
    ' */',
    'export const pkitsTests: { id: string; title: string; path: string[] }[] = [',
]
for test in tests:
    out.append(
        f"    {{ id: '{test['id']}', title: {json.dumps(test['title'])}, path: {json.dumps(test['path'])} }},"
    )
out += [']', '']
sys.stdout.write('\n'.join(out))
print(f'{len(tests)} tests, {len(names)} files', file=sys.stderr)
