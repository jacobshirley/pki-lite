"""Writes pkits-smime.ts from the PKITS S/MIME messages (section 6.2).

usage: emit-smime.py <data dir> > pkits-smime.ts

Every test in section 4 has a signed message, Signed<test name>.eml: multipart/signed
(RFC 1847) with the signer's certificates and the CRLs of its path in the signature. For
each, this writes the signed content (the first MIME part, line endings canonicalised to
CRLF as S/MIME signs it) and the detached signature (a CMS ContentInfo), as base64.
"""

import base64
import json
import os
import re
import sys

data_dir = sys.argv[1]
smime_dir = f'{data_dir}/smime'

messages = {}
for name in sorted(os.listdir(smime_dir)):
    if not name.endswith('.eml'):
        continue
    raw = open(f'{smime_dir}/{name}', 'rb').read().replace(b'\r\n', b'\n')
    boundary = re.search(rb'boundary="([^"]+)"', raw).group(1)
    delimiter = b'\n--' + boundary
    parts = raw.split(delimiter)
    # parts[0] is the preamble, then each part starts with the rest of its delimiter line
    signed, signature = parts[1], parts[2]
    # the part starts after the delimiter line; the newline before the next delimiter
    # belongs to the delimiter (RFC 2046 5.1.1)
    signed = signed[signed.index(b'\n') + 1 :]
    content = signed.replace(b'\n', b'\r\n')

    header, body = signature.split(b'\n\n', 1)
    assert b'application/pkcs7-signature' in header, name
    der = base64.b64decode(b''.join(body.split()))

    test = name[len('Signed') : -len('.eml')]
    messages[test] = {
        'content': base64.b64encode(content).decode(),
        'signature': base64.b64encode(der).decode(),
    }

print(f'''// Generated by generate.sh from the NIST PKITS S/MIME messages; do not edit.
// For each test (by name, letters and digits only): the signed content (base64, CRLF line endings)
// and the detached signature (base64 DER CMS ContentInfo).

export const pkitsMessages: Record<string, {{ content: string; signature: string }}> = {json.dumps(messages, indent=4)}''')
