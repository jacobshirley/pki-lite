#!/usr/bin/env bash
# Emits corpus.ts (base64 per file) from a directory of <family>/<file> DER files.
#   emit-ts.sh <corpus-dir> > corpus.ts
set -eu
DIR="${1:?corpus dir}"
echo "// Generated by generate.sh from OpenSSL output. Do not edit."
echo "// Each entry is the base64 of one DER file; see README.md."
echo "export const opensslCorpus: Record<string, Record<string, string>> = {"
for family in cert csr crl key cms p12 ocsp ts; do
  echo "    ${family}: {"
  for f in $(ls "$DIR/$family" | LC_ALL=C sort); do
    printf "        '%s': '%s',\n" "$f" "$(openssl base64 -A -in "$DIR/$family/$f")"
  done
  echo "    },"
done
echo "}"
